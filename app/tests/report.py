"""Run the required cases in mock mode and print (and save) the table of outcome, amount and tier against what is expected.

    python app/tests/report.py            # writes app/tests/RESULTS.md
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from fairryde_app import cases, llm, pipeline      # noqa: E402

REQUIRED = ["DISP-001", "DISP-002", "DISP-003", "E01", "E02", "E03", "E04", "E10", "E11"]


def money(x):
    return "none" if x in (None, 0, 0.0) else f"S${x:.2f}"


def build_table(mode: str = "mock") -> tuple[str, bool]:
    rows, ok_all = [], True
    for cid in REQUIRED:
        info = cases.get_info(cid)
        run = pipeline.run_case(cid, mode=mode, save=False)
        r, x = run["result"], info.expected
        ok = run["expected_check"]["ok"]
        ok_all &= ok
        mark = lambda good: "yes" if good else "NO"
        ec = run["expected_check"]
        rows.append(f"| {cid} | {info.dispute_type} | {x['outcome']} | {r['outcome']} | {money(x['amount_sgd'])} | {money(r['amount_sgd'])} | {x['tier']} | {r['tier']} | "
                    f"{mark(ec['outcome_ok'])} / {mark(ec['amount_ok'])} / {mark(ec['tier_ok'])} | {r['status'].lower()}{', gate ' + r['gate'] if r['gate'] else ''} |")
    head = ("| Case | Dispute type | Expected outcome | Outcome | Expected amount | Amount | Expected tier | Tier | Match (outcome / amount / tier) | Status |\n"
            "|---|---|---|---|---|---|---|---|---|---|")
    return head + "\n" + "\n".join(rows), ok_all


if __name__ == "__main__":
    table, ok = build_table("mock")
    text = ("# Test results: required cases, mock mode\n\nGenerated by `python app/tests/report.py` (saved responses, no API key). "
            "Expected values: organizer samples from `kb/organizer_cases.yaml`; E01 to E11 outcome and amount from `validation/V4_e2e/42_reference.jsonl`, "
            "tier from the A6 engine rerun (`validation/build_checks/A6/01_engine_rerun.json`), HUMAN where the settled reference says a person decides (E10).\n\n" + table + "\n\n"
            f"All nine match: {'yes' if ok else 'NO'}.\n")
    (HERE / "RESULTS.md").write_text(text, encoding="utf-8")
    print(table)
    print("\nall nine match:", ok)
    sys.exit(0 if ok else 1)
